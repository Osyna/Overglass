#!/usr/bin/env python3
"""Regenerate the route table in docs/API.md from webos_foundry.server.ROUTES.

Maintainer tool: run after changing routes. `--check` exits 1 if the file is out of date.
Only the text between the ROUTES:BEGIN / ROUTES:END marker comments is replaced.
"""
import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "API.md"
BEGIN = "<!-- ROUTES:BEGIN"
END = "<!-- ROUTES:END -->"
HEADER = "(generated by scripts/gen_api_docs.py; edit the script's source, not this table) -->"


def load_routes():
    sys.path.insert(0, str(ROOT))
    try:
        from webos_foundry import server
    except ImportError as error:
        sys.exit("gen_api_docs: cannot import webos_foundry.server (%s). Install the package "
                 "(`pip install -e .`) and make sure server.py exists." % error)
    routes = getattr(server, "ROUTES", None)
    if not routes:
        sys.exit("gen_api_docs: webos_foundry.server has no ROUTES tuple")
    return routes


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ").strip()


def table(routes):
    rows = ["| Method | Path | Group | Summary |", "| --- | --- | --- | --- |"]
    for route in routes:
        try:
            rows.append("| `%s` | `%s` | %s | %s |" % (route["method"], route["path"], cell(route["group"]), cell(route["summary"])))
        except (KeyError, TypeError) as error:
            sys.exit("gen_api_docs: route %r lacks method/path/group/summary (%s)" % (route, error))
    return "\n".join(rows)


def render(text, routes):
    pattern = re.compile(re.escape(BEGIN) + r".*?-->\n.*?\n" + re.escape(END), re.S)
    if not pattern.search(text):
        sys.exit("gen_api_docs: %s lacks the ROUTES:BEGIN / ROUTES:END markers" % DOC)
    block = "%s %s\n\n%s\n\n%s" % (BEGIN, HEADER, table(routes), END)
    return pattern.sub(lambda _: block, text, count=1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/API.md is stale instead of rewriting it")
    args = parser.parse_args()
    if not DOC.is_file():
        sys.exit("gen_api_docs: %s not found" % DOC)
    old = DOC.read_text(encoding="utf-8")
    new = render(old, load_routes())
    if args.check:
        sys.exit(0 if new == old else "docs/API.md is out of date; run scripts/gen_api_docs.py")
    DOC.write_text(new, encoding="utf-8")
    print("updated", DOC)


if __name__ == "__main__":
    main()
